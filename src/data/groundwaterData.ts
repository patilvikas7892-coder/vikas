// Helper to compute Water Quality Index (WQI) score from any set of metrics
export function calculateWQI(metrics: {
  tds: number;
  ph: number;
  fluoride: number;
  nitrate: number;
  arsenic: number;
  hardness: number;
  iron: number;
}): { score: number; status: 'Excellent' | 'Good' | 'Fair' | 'Poor' | 'Unsafe'; potability: string } {
  let penalty = 0;

  // TDS penalty (Desirable 500, Max 2000)
  if (metrics.tds > 2000) penalty += 35;
  else if (metrics.tds > 1000) penalty += 20;
  else if (metrics.tds > 500) penalty += 10;

  // pH penalty (6.5 - 8.5)
  if (metrics.ph < 6.5 || metrics.ph > 8.5) {
    penalty += Math.min(25, Math.abs(metrics.ph - 7.5) * 15);
  }

  // Fluoride penalty (Max 1.0 desirable, 1.5 permissible)
  if (metrics.fluoride > 1.5) penalty += 35;
  else if (metrics.fluoride > 1.0) penalty += 15;

  // Nitrate penalty (Max 45)
  if (metrics.nitrate > 45) penalty += 30;
  else if (metrics.nitrate > 30) penalty += 10;

  // Arsenic penalty (Max 0.01) - severe carcinogen
  if (metrics.arsenic > 0.01) penalty += 50;

  // Hardness penalty (Desirable 200, Max 600)
  if (metrics.hardness > 600) penalty += 20;
  else if (metrics.hardness > 300) penalty += 10;

  // Iron penalty (Max 1.0)
  if (metrics.iron > 1.0) penalty += 20;

  const score = Math.max(10, Math.min(100, Math.round(100 - penalty)));

  let status: 'Excellent' | 'Good' | 'Fair' | 'Poor' | 'Unsafe' = 'Good';
  let potability = 'Directly Potable with Basic Filtration';

  if (score >= 85) {
    status = 'Excellent';
    potability = 'Directly Potable (Boil or Simple Carbon Filter)';
  } else if (score >= 70) {
    status = 'Good';
    potability = 'Safe with Standard Gravity / UV Purifier';
  } else if (score >= 50) {
    status = 'Fair';
    potability = 'Requires RO or Specific Heavy Mineral Filter';
  } else if (score >= 35) {
    status = 'Poor';
    potability = 'Mandatory RO + Mineral Cartridge; Not directly drinkable';
  } else {
    status = 'Unsafe';
    potability = 'HAZARDOUS: Do not consume without specialized plant treatment';
  }

  return { score, status, potability };
}

// Rooftop Rainwater Harvesting Calculator helper
export function calculateRWH(
  rooftopAreaSqFt: number,
  annualRainfallMm: number,
  roofTypeCoeff: number = 0.85 // RCC slab default
) {
  // 1 sq ft = 0.0929 sq meters
  const areaSqM = rooftopAreaSqFt * 0.092903;
  // Volume in Litres = Area (m2) * Rainfall (mm) * Runoff Coefficient
  const harvestableLitres = Math.round(areaSqM * annualRainfallMm * roofTypeCoeff);

  // Average Indian domestic drinking/cooking requirement: ~15 litres per person per day
  // Average 4-member household = 60 litres/day
  const householdDays = Math.round(harvestableLitres / 60);

  // Recommended recharge pit size:
  // For ~1000 sq ft roof, recommended pit is 1.5m x 1.5m x 2.0m depth filled with filter media
  const volumeCubicMeters = Math.max(2, Math.round((areaSqM * 0.02) * 10) / 10);

  return {
    harvestableLitres,
    householdDays,
    volumeCubicMeters,
    co2EquivalentOffsetKg: Math.round(harvestableLitres * 0.0003), // Pumping energy saved
  };
}
